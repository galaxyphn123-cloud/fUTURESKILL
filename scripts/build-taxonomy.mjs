/* Generates src/data/taxonomy.js: per skill, 10 ordered micro-skills (strands of
   10 consecutive activities), named after the dominant per-activity label.
   Age bands and prerequisites are a first-pass heuristic (age_source:"heuristic")
   meant to be edited by a curriculum owner; everything else is derived. */
import fs from "node:fs";
import { DOMAINS } from "../src/data/domains.js";
import { SKILL_CONTENT } from "../src/data/skillContent.js";

const AGES = ["A", "B", "C", "D", "E"];
const out = {};
for (const d of DOMAINS) {
  d.skills.forEach((s, i) => {
    const acts = SKILL_CONTENT[s.id];
    const micro = [];
    for (let b = 0; b < 10; b++) {
      const block = acts.slice(b * 10, b * 10 + 10);
      const freq = new Map();
      block.forEach(a => freq.set(a.micro, (freq.get(a.micro) || 0) + 1));
      let name = block[0].micro, best = 0;
      for (const [k, v] of freq) if (v > best) { best = v; name = k; }
      if (micro.some(m => m.name === name)) name = `${name} (${b + 1})`;
      micro.push({ id: `${s.id}.${String(b + 1).padStart(2, "0")}`, name, range: [b * 10 + 1, b * 10 + 10] });
    }
    // Math is strictly sequential by grade; other domains spread their 8-9 skills over A..D.
    const band = d.id === "MATH" ? Math.min(4, Math.floor((i / d.skills.length) * 5))
                                 : Math.min(3, Math.floor((i / d.skills.length) * 4));
    out[s.id] = {
      id: s.id, domain: d.id, name: s.name, micro,
      age_entry: AGES[band], age_source: "heuristic",
      prerequisite_skill: i === 0 ? null : d.skills[i - 1].id,
    };
  });
}
fs.writeFileSync(new URL("../src/data/taxonomy.js", import.meta.url),
  "/* GENERATED by scripts/build-taxonomy.mjs — edit age_entry/prerequisite_skill/micro names here by hand if needed;\n   re-running the script overwrites. */\nexport const TAXONOMY = " + JSON.stringify(out, null, 1) + ";\n");
console.log("skills:", Object.keys(out).length, "micro-skills:", Object.values(out).reduce((s, x) => s + x.micro.length, 0));
